"""Build synthetic payslips with known, injected underpayments.

Each sample = roster + correct entitlement (from the rules engine) + what the employer "paid"
(entitlement with 0-2 injected errors) + a payslip in one of three styles + exact ground truth.
Everything is driven by one seed, so a dataset can be regenerated byte for byte.
"""

from __future__ import annotations

import random
from datetime import date, timedelta
from decimal import Decimal
from typing import Any

from pydantic import BaseModel

from wagecheck.engine import Calculator
from wagecheck.holidays import nsw_holidays
from wagecheck.models import EmployeeProfile, EmploymentType, Shift
from wagecheck.rules.loader import load_pack
from wagecheck.synth.errors import (
    INJECTORS,
    NEEDS_LONG_SHIFT,
    NEEDS_SHORT_SHIFT,
    Context,
    PaidLine,
    expected_lines,
    total,
)
from wagecheck.synth.payslip import STYLES, Payslip, aggregate, totals
from wagecheck.synth.scenarios import SCENARIOS, Scenario, roster

FIRST = ["Aarav", "Priya", "Wei", "Mei", "Lucas", "Sofia", "Kofi", "Amara", "Hiroshi", "Yuki", "Diego", "Lucia",
         "Arjun", "Nisha", "Tom", "Grace", "Omar", "Layla", "Minh", "Linh", "Rahul", "Ananya", "Jack", "Chloe"]
LAST = ["Sharma", "Chen", "Nguyen", "Silva", "Mensah", "Tanaka", "Garcia", "Patel", "Kim", "Smith", "Haddad",
        "Rossi", "Okafor", "Singh", "Tran", "Brown", "Iyer", "Lopez", "Wong", "Murphy"]
FIRST_MONDAY = date(2026, 7, 6)   # first full week on the 1 July 2026 rates
LAST_MONDAY = date(2027, 3, 1)    # stay inside FY2026-27


class InjectedError(BaseModel):
    kind: str
    detail: str
    dates: list[str]
    shortfall: Decimal


class Sample(BaseModel):
    id: str
    scenario: str
    award: str
    classification: str
    employment: str
    shiftworker: bool
    shifts: list[Shift]
    payslip: Payslip
    expected_gross: Decimal
    paid_gross: Decimal
    shortfall: Decimal
    errors: list[InjectedError]
    expected_lines: list[dict[str, Any]]
    paid_lines: list[dict[str, Any]]


def fake_abn(rng: random.Random) -> str:
    """11 digits that deliberately FAIL the ATO checksum, so a synthetic ABN can never be a real business."""
    from wagecheck.coverage.identity import abn_is_valid

    while True:
        digits = "".join(str(rng.randint(0, 9)) for _ in range(11))
        if digits[0] != "0" and not abn_is_valid(digits):
            return f"{digits[:2]} {digits[2:5]} {digits[5:8]} {digits[8:]}"


def _pick_errors(rng: random.Random) -> list[str]:
    n = rng.choices([0, 1, 2], weights=[30, 50, 20])[0]
    return rng.sample(sorted(INJECTORS), n)


def _line_dict(ln: PaidLine) -> dict[str, Any]:
    return {"shift": ln.shift_index, "date": str(ln.work_date), "band": ln.band, "true_band": ln.true_band,
            "minutes": ln.minutes, "percent": str(ln.percent), "rate": str(ln.rate), "amount": str(ln.amount)}


def generate_one(idx: int, seed: int) -> Sample:
    rng = random.Random(seed * 100_003 + idx)
    for _attempt in range(20):
        scenario: Scenario = rng.choice(SCENARIOS)
        employment = rng.choice(scenario.employment)
        classification = rng.choice(scenario.classifications)
        wanted = _pick_errors(rng)
        weeks = rng.choice([1, 2])
        start = FIRST_MONDAY + timedelta(weeks=rng.randint(0, (LAST_MONDAY - FIRST_MONDAY).days // 7 - weeks))
        shifts = roster(scenario, start, 7 * weeks, rng,
                        need_short=bool(NEEDS_SHORT_SHIFT & set(wanted)),
                        need_long=bool(NEEDS_LONG_SHIFT & set(wanted)))
        pack = load_pack(scenario.award, start)
        profile = EmployeeProfile(classification=classification, employment_type=employment,
                                  shiftworker=scenario.shiftworker, extended_trading=scenario.extended_trading)
        calc = Calculator(pack, nsw_holidays())
        ctx = Context(pack, classification, employment, [calc.calculate(s, profile) for s in shifts])

        expected = expected_lines(ctx)
        paid, errors = expected, []
        for kind in wanted:
            out = INJECTORS[kind](paid, ctx, rng)
            if out is None:
                break
            new, inj = out
            shortfall = total(paid) - total(new)
            if shortfall <= 0:
                break
            errors.append(InjectedError(kind=inj.kind, detail=inj.detail, dates=inj.dates, shortfall=shortfall))
            paid = new
        else:
            return _assemble(idx, rng, scenario, classification, employment, start, weeks, shifts, expected, paid,
                             errors, ctx)
    raise RuntimeError(f"could not build sample {idx}")


def _assemble(idx: int, rng: random.Random, scenario: Scenario, classification: str, employment: EmploymentType,
              start: date, weeks: int, shifts: list[Shift], expected: list[PaidLine], paid: list[PaidLine],
              errors: list[InjectedError], ctx: Context) -> Sample:
    style = rng.choice(STYLES)
    casual = employment is EmploymentType.CASUAL
    lines = aggregate(paid, casual, style)
    gross, tax, net, sup = totals(lines)
    end = start + timedelta(days=7 * weeks - 1)
    payslip = Payslip(
        employer_name=rng.choice(scenario.employer_names) + " Pty Ltd",
        employer_abn=fake_abn(rng),
        employee_name=f"{rng.choice(FIRST)} {rng.choice(LAST)}",
        employee_id=str(rng.randint(100000, 999999)),
        job_title=scenario.job_title,
        classification_label=classification.replace("_", " ").title(),
        employment_type={"casual": "Casual", "part_time": "Part-time", "full_time": "Full-time"}[employment.value],
        award_named=ctx.pack.title if rng.random() < 0.4 else None,
        period_start=start, period_end=end, pay_date=end + timedelta(days=rng.choice([3, 4, 5])),
        lines=lines, gross=gross, tax=tax, net=net, super_amount=sup, style=style,
    )
    exp_total, paid_total = total(expected), total(paid)
    assert gross == paid_total
    return Sample(
        id=f"syn-{idx:05d}", scenario=scenario.key, award=scenario.award, classification=classification,
        employment=employment.value, shiftworker=scenario.shiftworker, shifts=shifts, payslip=payslip,
        expected_gross=exp_total, paid_gross=paid_total, shortfall=exp_total - paid_total, errors=errors,
        expected_lines=[_line_dict(ln) for ln in expected], paid_lines=[_line_dict(ln) for ln in paid],
    )


def generate(n: int, seed: int = 42) -> list[Sample]:
    return [generate_one(i, seed) for i in range(n)]


def check_sample(s: Sample) -> list[str]:
    """Invariants every sample must satisfy (used by tests and by the CLI after generating)."""
    problems = []
    if s.expected_gross - s.paid_gross != s.shortfall:
        problems.append("shortfall != expected - paid")
    if sum((e.shortfall for e in s.errors), Decimal(0)) != s.shortfall:
        problems.append("error shortfalls don't add up")
    if not s.errors and s.shortfall != 0:
        problems.append("clean payslip with a shortfall")
    if s.payslip.gross != s.paid_gross:
        problems.append("payslip gross != paid lines")
    return problems
